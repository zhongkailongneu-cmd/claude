// Brain geometry for the two schematic views, in a 1000 x 820 "brain space".
// Both views face left (anterior = left, posterior = right).
//
// Lobes are assembled from shared boundary curves (outline segments and
// the central / lateral / parieto-occipital boundaries) so neighbouring
// regions meet exactly with no gaps. Sub-regions (DLPFC, ACC ...) are
// "masks": a rough polygon that is clipped by the lobe it belongs to at
// draw time, so the outer edge always follows the anatomy.

// ---- curve helpers -------------------------------------------------------
export function catmull(pts, closed = false, steps = 10) {
  const out = [];
  const n = pts.length;
  const get = (i) => {
    if (closed) return pts[(i + n) % n];
    return pts[Math.max(0, Math.min(n - 1, i))];
  };
  const segs = closed ? n : n - 1;
  for (let i = 0; i < segs; i++) {
    const p0 = get(i - 1), p1 = get(i), p2 = get(i + 1), p3 = get(i + 2);
    for (let s = 0; s < steps; s++) {
      const t = s / steps, t2 = t * t, t3 = t2 * t;
      const x = 0.5 * (2 * p1[0] + (-p0[0] + p2[0]) * t + (2 * p0[0] - 5 * p1[0] + 4 * p2[0] - p3[0]) * t2 + (-p0[0] + 3 * p1[0] - 3 * p2[0] + p3[0]) * t3);
      const y = 0.5 * (2 * p1[1] + (-p0[1] + p2[1]) * t + (2 * p0[1] - 5 * p1[1] + 4 * p2[1] - p3[1]) * t2 + (-p0[1] + 3 * p1[1] - 3 * p2[1] + p3[1]) * t3);
      out.push([x, y]);
    }
  }
  if (!closed) out.push(pts[n - 1].slice());
  return out;
}

const rev = (a) => a.slice().reverse();
// join curves that share end points (drops the duplicated first point of each next curve)
const join = (...segs) => segs.reduce((acc, s) => acc.concat(acc.length ? s.slice(1) : s), []);
const cat = (...segs) => [].concat(...segs);
const smooth = (pts) => catmull(pts, true, 8);

export function polyPath(pts, closed = true) {
  const p = new Path2D();
  pts.forEach(([x, y], i) => (i ? p.lineTo(x, y) : p.moveTo(x, y)));
  if (closed) p.closePath();
  return p;
}

export function ellipsePts(cx, cy, rx, ry, rot = 0, n = 48) {
  const out = [];
  for (let i = 0; i < n; i++) {
    const a = (i / n) * Math.PI * 2;
    const x = Math.cos(a) * rx, y = Math.sin(a) * ry;
    out.push([cx + x * Math.cos(rot) - y * Math.sin(rot), cy + x * Math.sin(rot) + y * Math.cos(rot)]);
  }
  return out;
}

// Filled polygon that looks like a pen stroke: wide in the middle, tapered at both ends.
export function taper(pts, width, steps = 8) {
  const c = catmull(pts, false, steps);
  const left = [], right = [];
  for (let i = 0; i < c.length; i++) {
    const a = c[Math.max(0, i - 1)], b = c[Math.min(c.length - 1, i + 1)];
    let dx = b[0] - a[0], dy = b[1] - a[1];
    const len = Math.hypot(dx, dy) || 1;
    dx /= len; dy /= len;
    const s = i / (c.length - 1);
    const w = (width / 2) * Math.pow(Math.sin(Math.PI * s), 0.55);
    left.push([c[i][0] - dy * w, c[i][1] + dx * w]);
    right.push([c[i][0] + dy * w, c[i][1] - dx * w]);
  }
  return left.concat(rev(right));
}

// Tube of varying width along a centre line (used for hippocampus / fornix).
export function tube(pts, w0, w1, steps = 10) {
  const c = catmull(pts, false, steps);
  const left = [], right = [];
  for (let i = 0; i < c.length; i++) {
    const a = c[Math.max(0, i - 1)], b = c[Math.min(c.length - 1, i + 1)];
    let dx = b[0] - a[0], dy = b[1] - a[1];
    const len = Math.hypot(dx, dy) || 1;
    dx /= len; dy /= len;
    const s = i / (c.length - 1);
    const w = (w0 + (w1 - w0) * s) / 2;
    left.push([c[i][0] - dy * w, c[i][1] + dx * w]);
    right.push([c[i][0] + dy * w, c[i][1] - dx * w]);
  }
  return left.concat(rev(right));
}

